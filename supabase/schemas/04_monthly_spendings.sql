create table public.monthly_spendings (
  id bigint generated by default as identity not null,
  created_at timestamptz not null default now(),
  reason varchar not null,
  amount integer not null,
  unit_id varchar,
  month date not null,
  chargeable boolean,
  -- "forAB" is the old camelCase name, kept in sync by a trigger until every
  -- deployed bundle writes for_ab. Dropped in a later migration.
  "forAB" boolean,
  for_ab boolean,
  constraint monthly_spendings_pkey primary key (id),
  constraint monthly_spendings_unit_id_month_fkey foreign key (unit_id, month)
    references public.monthly_rents (unit_id, month),
  constraint monthly_spendings_amount_positive check (amount > 0),
  constraint monthly_spendings_reason_not_blank check (btrim(reason::text) <> ''),
  constraint monthly_spendings_month_is_first_of_month
    check (month = (date_trunc('month', month::timestamptz))::date),
  -- A general spending (no unit) has no tenant to charge
  constraint monthly_spendings_general_not_chargeable
    check (unit_id is not null or chargeable is not true)
);

create index monthly_spendings_unit_id_month_idx on public.monthly_spendings (unit_id, month);

alter table public.monthly_spendings enable row level security;

create policy "Owner full access" on public.monthly_spendings
  as permissive for all to authenticated
  using (true) with check (true);

grant select, insert, update, delete, truncate, references, trigger on public.monthly_spendings to authenticated;

-- Transitional: keeps "forAB" and for_ab in step so a cached old bundle and a freshly
-- deployed one can both write spendings during the rollout window.
create function public.monthly_spendings_sync_for_ab()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    if new.for_ab is null and new."forAB" is not null then
      new.for_ab := new."forAB";
    elsif new."forAB" is null and new.for_ab is not null then
      new."forAB" := new.for_ab;
    end if;
  else
    if new.for_ab is distinct from old.for_ab then
      new."forAB" := new.for_ab;
    elsif new."forAB" is distinct from old."forAB" then
      new.for_ab := new."forAB";
    end if;
  end if;
  return new;
end
$$;

create trigger monthly_spendings_sync_for_ab
  before insert or update on public.monthly_spendings
  for each row execute function public.monthly_spendings_sync_for_ab();
