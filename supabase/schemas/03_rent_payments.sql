create table public.rent_payments (
  id bigint generated by default as identity not null,
  unit_id varchar not null,
  month date not null,
  amount integer not null,
  created_at timestamptz not null default now(),
  constraint rent_payments_pkey primary key (id),
  constraint rent_payments_unit_id_month_fkey foreign key (unit_id, month)
    references public.monthly_rents (unit_id, month),
  constraint rent_payments_amount_positive check (amount > 0),
  constraint rent_payments_month_is_first_of_month
    check (month = (date_trunc('month', month::timestamptz))::date)
);

create index rent_payments_unit_id_month_idx on public.rent_payments (unit_id, month);

alter table public.rent_payments enable row level security;

create policy "Owner full access" on public.rent_payments
  as permissive for all to authenticated
  using (true) with check (true);

grant select, insert, update, delete, truncate, references, trigger on public.rent_payments to authenticated;
